#!/usr/bin/env node
/** Production slot wiring, one-shot commands, draft-safe fills, result actions and focus. */
import assert from 'node:assert/strict'
import { mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { build } from 'esbuild'
import { connectCdp, launchChrome, startStaticServer } from '../support/browser.mjs'

const root = new URL('../../', import.meta.url).pathname
const temp = await mkdtemp(join(tmpdir(), 'iui-on-demand-e2e-'))
let server, browser, cdp
let checks = 0
const check = (value, expected, message) => { assert.deepEqual(value, expected, message); checks++ }
try {
  await build({
    entryPoints: [join(root, 'test/browser/harness/on-demand-entry.tsx')], outfile: join(temp, 'bundle.js'),
    bundle: true, platform: 'browser', format: 'esm', target: 'chrome120', jsx: 'automatic', absWorkingDir: root,
    define: { 'process.env.NODE_ENV': '"production"' }, logLevel: 'silent',
    plugins: [{ name: 'shell-icons', setup(build) {
      build.onResolve({ filter: /^@deepseek-ai\/dsh-client-ui-primitives$/ }, () => ({ path: 'icons', namespace: 'fixture' }))
      build.onLoad({ filter: /.*/, namespace: 'fixture' }, () => ({ contents: 'export const DisclosureRow = () => null; export const IconChevronDownOutlineRegular = () => null; export const IconSparkleRegular = () => null' }))
    } }],
  })
  await writeFile(join(temp, 'index.html'), `<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="bundle.css"><style>
:root { color-scheme:light; --dsw-alias-bg-layer-1:#fff; --dsw-alias-bg-layer-2:#f2f2f2; --dsw-alias-label-primary:#171717; --dsw-alias-label-secondary:#555; --dsw-alias-border-l1:#ddd; --dsw-alias-border-l2:#ccc; --dsw-alias-interactive-bg-hover:#eee; --dsw-alias-state-error-primary:#b42318; --dsw-radius-sm:6px; --dsw-radius-md:10px; --dsw-radius-lg:14px; --dsw-focus-ring-color:#1265bb; --dsw-focus-ring-width:2px; --dsw-font-family:system-ui; }
body[data-ds-dark-theme] { color-scheme:dark; --dsw-alias-bg-layer-1:#1b1b1b; --dsw-alias-bg-layer-2:#242424; --dsw-alias-label-primary:#f2f2f2; --dsw-alias-label-secondary:#b8b8b8; --dsw-alias-border-l1:#323232; --dsw-alias-border-l2:#3c3c3c; --dsw-alias-interactive-bg-hover:#2e2e2e; }
body { margin:0; background:var(--dsw-alias-bg-layer-1); color:var(--dsw-alias-label-primary); font:14px system-ui; } main { margin:24px auto; max-width:680px; }
[data-composer-card] { position:fixed; bottom:20px; left:20px; right:20px; max-width:680px; margin:auto; border:1px solid var(--dsw-alias-border-l2); border-radius:14px; background:var(--dsw-alias-bg-layer-1); }
[data-composer-overlay] { height:0; position:absolute; inset:0 0 auto; } [contenteditable] { min-height:48px; padding:10px; outline-offset:-3px; white-space:pre-wrap; } .toolbar { display:flex; justify-content:flex-end; padding:8px; }
</style></head><body><div id="root"></div><script type="module" src="bundle.js"></script></body></html>`)
  server = await startStaticServer(temp)
  browser = await launchChrome({ url: server.url, width: 900, height: 850 })
  assert.ok(browser, 'Chrome required')
  cdp = await connectCdp(browser.port)
  await cdp.send('Page.enable'); await cdp.send('Runtime.enable')
  const read = expression => cdp.evaluate(expression)
  const wait = expression => cdp.waitFor(expression, expression)
  const click = selector => read(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const focus = () => read('document.activeElement === document.querySelector("[contenteditable]")')
  const draft = () => read('document.querySelector("[contenteditable]").textContent')
  const project = async (status, extra = {}) => {
    await read(`window.__project(${JSON.stringify({ operationId: 'operation-1', kind: 'generate', status, clientInstanceId: await read('window.__token'), resultIds: [], ...extra })})`)
  }
  const open = async () => {
    await click('[data-dsh-iui-toggle]')
    await wait('!!document.querySelector("[data-style-entry]")')
    await click('[data-style-entry]')
    await wait('!!document.querySelector("[data-dsh-iui-on-demand-entry]")')
  }
  await wait('!!document.querySelector("[data-dsh-iui-toggle]")')
  await open()
  check(await read('document.querySelector("[data-dsh-iui-on-demand-entry]").textContent.includes("On-demand UI")'), true, 'entry visible')
  await read('window.__failure = "Host rejected arming"')
  await click('[data-dsh-iui-on-demand-entry]')
  await wait('!!document.querySelector("[role=alert]")')
  check(await read('!!document.querySelector("[data-dsh-iui-style-panel]")'), true, 'failure retains panel')
  check(await read('document.querySelector("[role=alert]").textContent'), 'Could not start on-demand UI: Host rejected arming')
  await read('window.__failure = ""; window.__delay = true')
  await click('[data-dsh-iui-on-demand-entry]')
  await wait('document.querySelector("[data-dsh-iui-on-demand-entry]").disabled')
  check(await read('!!document.querySelector("[data-dsh-iui-style-panel]")'), true, 'pending retains panel')
  await read('window.__delay = false; window.__settle()')
  await wait('!document.querySelector("[data-dsh-iui-style-panel]")')
  check(await read('window.__calls.at(-1)'), { sessionId: 'e2e-session', command: `/iui on-demand ${await read('window.__token')}`, attachments: [] })
  await wait('document.activeElement === document.querySelector("[contenteditable]")')
  check(await read('!!document.querySelector("[data-dsh-iui-on-demand-hint]")'), false, 'no optimistic hint')
  await project('armed', { clientInstanceId: 'another-tab' })
  check(await read('!!document.querySelector("[data-dsh-iui-on-demand-hint]")'), false, 'other tab is isolated')
  await project('armed')
  await wait('!!document.querySelector("[data-dsh-iui-on-demand-hint]")')
  check(await read('document.querySelectorAll(".dsh-iui-on-demand-examples button").length'), 4)
  await writeFile('/tmp/iui-r2-hint.png', Buffer.from((await cdp.send('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  const example = await read('document.querySelector(".dsh-iui-on-demand-examples button").textContent')
  await read('document.querySelector(".dsh-iui-on-demand-examples button").focus()')
  await cdp.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, text: '\r' })
  await cdp.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })
  check(await draft(), example)
  check(await focus(), true)
  await read('window.__draft("Existing draft")')
  await click('.dsh-iui-on-demand-examples button')
  check(await draft(), `Existing draft\n${example}`, 'selection cannot replace text')
  check(await read('window.__submits'), 0)
  await cdp.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape' })
  await click('main')
  check(await draft(), `Existing draft\n${example}`, 'Escape/outside leaves draft alone')
  check(await read('!!document.querySelector("[data-dsh-iui-on-demand-hint]")'), true)
  await read('window.__failure = "Cancel refused"')
  await click('.dsh-iui-on-demand-cancel')
  await wait('!!document.querySelector(".dsh-iui-on-demand-hint [role=alert]")')
  check(await read('document.querySelector(".dsh-iui-on-demand-hint [role=alert]").textContent.includes("Cancel refused")'), true)
  await read('window.__failure = ""')
  await click('.dsh-iui-on-demand-cancel')
  await wait('!document.querySelector(".dsh-iui-on-demand-cancel").disabled')
  check(await read('window.__calls.at(-1).command'), '/iui on-demand off')
  await project('cancelled')
  await wait('!document.querySelector("[data-dsh-iui-on-demand-hint]")')
  for (const [status, copy] of [['running', 'Building the UI'], ['clarifying', 'Waiting for your answer']]) {
    await project(status)
    await wait('!!document.querySelector("[data-dsh-iui-on-demand-hint]")')
    if (status === 'running') await writeFile('/tmp/iui-on-demand-running.png', Buffer.from((await cdp.send('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
    check(await read('document.querySelector("[data-dsh-iui-on-demand-hint]").dataset.status'), status, `${status} status`)
    check(await read(`document.querySelector("[data-dsh-iui-on-demand-hint]").textContent.includes(${JSON.stringify(copy)})`), true, `${status} copy`)
    check(await read('!!document.querySelector(".dsh-iui-on-demand-cancel")'), false, `${status} has no cancel`)
    check(await read('document.querySelectorAll(".dsh-iui-on-demand-examples button").length'), 0, `${status} has no examples`)
  }
  await project('completed')
  check(await read('!!document.querySelector("[data-dsh-iui-on-demand-hint]")'), false, 'completed clears the hint')
  await project('failed')
  await wait('!!document.querySelector("[data-dsh-iui-on-demand-hint]")')
  check(await read('document.querySelector("[data-dsh-iui-on-demand-hint]").textContent.includes("finished without a result")'), true, 'failed guidance')
  check(await read('!!document.querySelector(".dsh-iui-on-demand-retry") && !!document.querySelector(".dsh-iui-on-demand-dismiss")'), true, 'failed offers retry and dismiss')
  await click('.dsh-iui-on-demand-dismiss')
  check(await read('!!document.querySelector("[data-dsh-iui-on-demand-hint]")'), false, 'dismiss hides the failed hint')
  await project('failed', { operationId: 'operation-2' })
  await wait('!!document.querySelector(".dsh-iui-on-demand-retry")')
  await click('.dsh-iui-on-demand-retry')
  await wait('document.querySelector(".dsh-iui-on-demand-retry").disabled === false')
  check(await read('window.__calls.at(-1).command'), `/iui on-demand ${await read('window.__token')}`, 'retry re-arms the operation')
  await project('failed', { operationId: 'operation-4', kind: 'adjust', parentResultId: 'call:previous-1' })
  await wait('!!document.querySelector(".dsh-iui-on-demand-retry")')
  await click('.dsh-iui-on-demand-retry')
  await wait('document.querySelector(".dsh-iui-on-demand-retry").disabled === false')
  check(await read('window.__calls.at(-1).command'), `/iui on-demand ${await read('window.__token')} adjust call:previous-1`, 'adjustment retry keeps the parent result')
  await project('interrupted', { operationId: 'operation-3' })
  await wait('!!document.querySelector("[data-dsh-iui-on-demand-hint]")')
  check(await read('document.querySelector("[data-dsh-iui-on-demand-hint]").textContent.includes("interrupted")'), true, 'interrupted guidance')
  check(await read('!!document.querySelector(".dsh-iui-on-demand-retry") && !!document.querySelector(".dsh-iui-on-demand-dismiss")'), true, 'interrupted offers retry and dismiss')
  await click('.dsh-iui-on-demand-dismiss')
  check(await read('!!document.querySelector("[data-dsh-iui-on-demand-hint]")'), false, 'dismiss hides the interrupted hint')
  await project('armed', { resume: true })
  await wait('!!document.querySelector("[data-dsh-iui-on-demand-hint]")')
  check(await read('document.querySelector("[data-dsh-iui-on-demand-hint]").textContent.includes("still active")'), true, 'resume copy')
  check(await read('document.querySelectorAll(".dsh-iui-on-demand-examples button").length'), 0, 'resume hides examples')
  await project('cancelled')
  check(await read('!!document.querySelector("[data-dsh-iui-on-demand-hint]")'), false, 'cancelled after resume')
  await project('armed', { clientInstanceId: undefined })
  await wait('!!document.querySelector("[data-dsh-iui-on-demand-hint]")')
  // Compact strip remains in the composer flow, in both schemes and narrow widths.
  for (const dark of [false, true]) {
    await read(`document.body.toggleAttribute('data-ds-dark-theme', ${dark})`)
    await cdp.send('Emulation.setDeviceMetricsOverride', { width: 360, height: 800, deviceScaleFactor: 1, mobile: false })
    const bounds = await read(`(() => {
      const h=document.querySelector('[data-dsh-iui-on-demand-hint]').getBoundingClientRect(), e=document.querySelector('[contenteditable]').getBoundingClientRect();
      return { fits:h.left>=0 && h.right<=innerWidth, above:h.bottom<=e.top, overflow:document.documentElement.scrollWidth>innerWidth }
    })()`)
    check(bounds, { fits: true, above: true, overflow: false })
  }
  await cdp.send('Emulation.clearDeviceMetricsOverride')
  await project('completed')
  check(await read('document.querySelector(".dsh-iui-temporary-badge").textContent'), 'Temporary style')
  check(await read('document.querySelector(".dsh-iui-result-actions button").textContent'), 'Adjust style')
  await read('window.__draft("Keep my draft"); window.__failure = "Adjustment refused"')
  const original = await read('document.querySelector("[data-dsh-iui-body]").textContent')
  await click('.dsh-iui-result-actions button')
  await wait('!!document.querySelector(".dsh-iui-result-actions [role=alert]")')
  check(await draft(), 'Keep my draft')
  check(await read('document.querySelector("[data-dsh-iui-body]").textContent'), original)
  await read('window.__failure = ""; window.__delay = true')
  await click('.dsh-iui-result-actions button')
  await wait('document.querySelector(".dsh-iui-result-actions button").disabled')
  await read('window.__draft("Typed while arming"); window.__delay = false; window.__settle()')
  await wait('!document.querySelector(".dsh-iui-result-actions button").disabled')
  check(await read('window.__calls.at(-1).command'), `/iui on-demand ${await read('window.__token')} adjust recorded-result-1`)
  check(await draft(), 'Typed while arming', 'late arm acknowledgment preserves the latest draft')
  check(await focus(), true)
  await read('window.__draft("")')
  await read('document.querySelector(".dsh-iui-result-actions button").focus()')
  check(await read('getComputedStyle(document.querySelector(".dsh-iui-result-actions button")).outlineStyle'), 'solid', 'adjust has visible keyboard focus')
  await cdp.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13, text: '\r' })
  await cdp.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })
  await wait('document.querySelector("[contenteditable]").textContent !== ""')
  check(await draft(), 'Adjust the style of this result: ')
  check(await focus(), true)
  check(await read('window.__submits'), 0)
  await read('window.__language("zh")')
  await project('armed')
  await wait('document.querySelector(".dsh-iui-temporary-badge").textContent === "临时样式"')
  check(await read('document.querySelector(".dsh-iui-result-actions button").textContent'), '调整样式')
  check(await read('document.querySelector(".dsh-iui-on-demand-heading strong").textContent'), '按需生成')
  await project('armed', { kind: 'adjust', parentResultId: 'recorded-result-1' })
  await wait('!document.querySelector(".dsh-iui-on-demand-examples")')
  check(await read('document.querySelector(".dsh-iui-on-demand-copy").textContent'), '描述想调整的样式，保留原有内容。')
  check(await read('document.body.textContent.includes("保存为模板")'), true)
  // Saving is optional, result-bound and does not submit or change styles.
  await project('completed')
  await read('window.__language("en")')
  const dialog = '.dsh-iui-style-popover[role=dialog]'
  const setField = async (selector, value) => read(`(() => {
    const input=document.querySelector(${JSON.stringify(selector)});
    Object.getOwnPropertyDescriptor(input.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(value)});
    input.dispatchEvent(new Event('input',{bubbles:true}));
  })()`)
  const popupButton = async label => read(`[...document.querySelectorAll('.dsh-iui-style-popover button')].find(b=>b.textContent===${JSON.stringify(label)}).click()`)
  const escape = () => read(`document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`)
  await click('[data-dsh-iui-save-result]')
  await wait(`!!document.querySelector('${dialog}')`)
  check(await read(`document.activeElement===document.querySelector('${dialog} input')`), true, 'save focuses name')
  check(await read(`document.querySelector('${dialog} input').value`), 'Compact')
  check(await read(`document.querySelectorAll('${dialog} input[type=radio]')[1].checked`), true, 'global save default')
  check(await read(`document.querySelector('${dialog} input').maxLength`), 30)
  check(await read(`document.querySelector('${dialog} textarea').maxLength`), 100)
  check(await read(`document.querySelector('${dialog}').parentElement===document.body`), true, 'save is portaled')
  await click(`${dialog} input[type=radio]`)
  check(await read(`document.querySelector('${dialog} input[type=radio]').checked`), true)
  await read(`document.querySelectorAll('${dialog} input[type=radio]')[1].click()`)
  // Both schemes fit the small laptop/mobile viewport without clipping the portal.
  for (const dark of [false, true]) {
    await read(`document.body.toggleAttribute('data-ds-dark-theme',${dark})`)
    await cdp.send('Emulation.setDeviceMetricsOverride', { width: 360, height: 800, deviceScaleFactor: 1, mobile: false })
    check(await read(`(()=>{const r=document.querySelector('${dialog}').getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight})()`), true)
    check(await read(`getComputedStyle(document.querySelector('${dialog}')).backgroundColor`), dark ? 'rgb(27, 27, 27)' : 'rgb(255, 255, 255)')
  }
  await cdp.send('Emulation.clearDeviceMetricsOverride')
  await read(`document.body.removeAttribute('data-ds-dark-theme')`)
  await escape(); await wait(`!document.querySelector('${dialog}')`)
  check(await read('document.activeElement.hasAttribute("data-dsh-iui-save-result")'), true)
  await click('[data-dsh-iui-save-result]'); await wait(`!!document.querySelector('${dialog}')`)
  await read(`document.querySelector('main').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))`)
  await wait(`!document.querySelector('${dialog}')`)
  check(await read('document.activeElement.hasAttribute("data-dsh-iui-save-result")'), true, 'outside dismissal restores focus')
  await click('[data-dsh-iui-save-result]'); await wait(`!!document.querySelector('${dialog}')`)
  await setField(`${dialog} input`, 'Reusable style')
  await setField(`${dialog} textarea`, 'For later answers')
  for (const code of ['duplicate_name', 'result_missing']) {
    await read(`window.__styleError=${JSON.stringify(code)}`)
    await popupButton('Save'); await wait(`!!document.querySelector('${dialog} [role=alert]')`)
    check(await read(`document.querySelector('${dialog} input').value`), 'Reusable style', 'retry preserves fields')
    check(await read(`document.querySelector('${dialog} [role=alert]').textContent.includes(${JSON.stringify(code === 'duplicate_name' ? 'already exists' : 'no longer available')})`), true)
  }
  await read(`window.__styleError='';window.__styleDelay=true`)
  const commandsBeforeSave = await read('window.__calls.length')
  await popupButton('Save'); await wait(`document.querySelector('${dialog} input').disabled`)
  check(await read(`document.querySelectorAll('${dialog} button')[1].disabled`), true)
  await read('window.__styleDelay=false;window.__styleSettle()')
  await wait(`!document.querySelector('${dialog}')`)
  check(await read('document.querySelector("[data-dsh-iui-save-result]").textContent'), 'Saved')
  check(await read('document.activeElement.hasAttribute("data-dsh-iui-save-result")'), true, 'save returns focus')
  check(await read('window.__stylePosts.at(-1)'), { op: 'saveFromResult', resultId: 'recorded-result-1', name: 'Reusable style', description: 'For later answers', scope: 'global' })
  check(await read('window.__calls.length'), commandsBeforeSave, 'saving never selects a style')
  check(await read('window.__submits'), 0, 'saving never regenerates')
  // The composer shares the manager; a nested portal must not dismiss its panel.
  await open()
  await wait('!!document.querySelector("[data-style-id=cs_saved001]")')
  await click('[data-style-id=cs_saved001]')
  await wait('document.querySelector("[data-style-id=cs_saved001]").getAttribute("aria-pressed")==="true"')
  const manage = '[data-dsh-iui-manage=cs_saved001]'
  const openMenu = async () => { await click(manage); await wait('!!document.querySelector(".dsh-iui-template-menu")') }
  await openMenu(); await popupButton('Rename')
  await wait(`!!document.querySelector('${dialog} input')`)
  await setField(`${dialog} input`, 'Renamed reusable')
  check(await read('!!document.querySelector("[data-dsh-iui-style-panel]")'), true, 'nested input retains parent panel')
  await popupButton('Save'); await wait(`!document.querySelector('${dialog}')`)
  await wait('document.querySelector("[data-style-id=cs_saved001]").textContent.includes("Renamed reusable")')
  check(await read('document.querySelector("[data-style-id=cs_saved001]").getAttribute("aria-pressed")'), 'true', 'rename keeps selection')
  await openMenu(); await popupButton('Edit preferences'); await wait(`!!document.querySelector('${dialog} textarea')`)
  await setField(`${dialog} textarea`, 'Edited description')
  await setField(`${dialog} textarea[maxlength="2000"]`, 'Use restrained color.\nKeep clear hierarchy.')
  await popupButton('Save'); await wait(`!document.querySelector('${dialog}')`)
  check(await read('window.__stylePosts.at(-1)'), { op: 'update', id: 'cs_saved001', patch: { description: 'Edited description', directives: 'Use restrained color.\nKeep clear hierarchy.' } })
  await openMenu(); await escape(); await wait('!document.querySelector(".dsh-iui-template-menu")')
  check(await read('!!document.querySelector("[data-dsh-iui-style-panel]")'), true, 'Escape dismisses only top popup')
  await openMenu(); await popupButton('Delete'); await wait(`!!document.querySelector('${dialog}')`)
  await popupButton('Cancel'); await wait(`!document.querySelector('${dialog}')`)
  check(await read('!!document.querySelector("[data-style-id=cs_saved001]")'), true)
  await openMenu(); await popupButton('Delete'); await wait(`!!document.querySelector('${dialog}')`)
  await read('window.__failure="Fallback failed"')
  await popupButton('Delete'); await wait(`!!document.querySelector('${dialog} [role=alert]')`)
  const deletes = await read('window.__stylePosts.filter(p=>p.op==="delete").length')
  await read('window.__failure=""')
  await popupButton('Delete'); await wait('!document.querySelector("[data-style-id=cs_saved001]")')
  check(await read('window.__stylePosts.filter(p=>p.op==="delete").length'), deletes, 'fallback retry does not delete twice')
  check(await read('window.__calls.at(-1).command'), '/iui style auto')
  check(await read('document.querySelector("[data-style-id=auto]").getAttribute("aria-pressed")'), 'true')
  check(await read('document.querySelector("[data-dsh-iui-body]").textContent'), original, 'management never changes historical content')
  await writeFile('/tmp/iui-r2-adjust.png', Buffer.from((await cdp.send('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  console.log(`on-demand E2E: OK (${checks} assertions; production slot/command/focus wiring, zh/en, light/dark, narrow layout)`)
} finally {
  cdp?.close(); await browser?.cleanup(); server?.close()
  await rm(temp, { recursive: true, force: true, maxRetries: 5, retryDelay: 120 })
}
