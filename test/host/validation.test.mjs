/**
 * Host structural validation: components and article anchors inside `@Each`.
 *
 * `@Each` templates are unresolved expression nodes (`{k:'Comp', name, args}`),
 * not element nodes. Before the traversal fix, a valid article program whose
 * Sections came from an `@Each` was rejected ("needs a Toc and at least one
 * Section", "missing Section target(s)"). These tests use the real parser and
 * the vendored library schema, so the AST shape matches production.
 *
 *   node --test test/host/validation.test.mjs
 */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'
import { createParser } from '@openuidev/lang-core'
import { articleAnchorError, collectArticleAnchors, collectComponentTypes, layoutWarnings } from '../../src/host/program-validation.ts'
import { anchorSlug } from '../../src/shared/anchor.ts'

const spec = JSON.parse(readFileSync(new URL('../../vendor/spec.json', import.meta.url), 'utf8'))
const parser = createParser(spec.schema, 'Col')

/** Parse one program and collect its component types and anchors. */
function inspect(program) {
  const result = parser.parse(program)
  assert.deepEqual(result.meta.errors ?? [], [], 'program should parse')
  const types = new Set()
  collectComponentTypes(result.root, types)
  const anchors = { section: [], toc: [], issues: [], dynamicSection: false, dynamicToc: false }
  collectArticleAnchors(result.root, anchors)
  return { types, anchors, error: articleAnchorError(anchors, types) }
}

test('Sections generated by @Each satisfy the article requirement', () => {
  const { types, anchors, error } = inspect(`root = Col([toc, @Each(days, "d", Section(d.title, [Markdown(d.body)]))])
toc = Toc(["Alpha", "Beta"])
days = [{title: "Alpha", body: "a"}, {title: "Beta", body: "b"}]`)
  assert.ok(types.has('Section'), 'dynamic Section must count as reachable')
  assert.ok(types.has('Toc'))
  assert.equal(anchors.dynamicSection, true)
  assert.equal(error, undefined, 'unverifiable dynamic anchors must not fail validation')
})

test('Toc generated by @Each does not fail on unseen anchors', () => {
  const { anchors, error } = inspect(`root = Col(@Each(groups, "g", Toc(g.items)))
groups = [{items: ["A"]}]`)
  assert.equal(anchors.dynamicToc, true)
  assert.equal(error, undefined)
})

test('static duplicate Section titles are still rejected', () => {
  const { error } = inspect(`root = Col([one, two])
one = Section("Background", [Markdown("a")])
two = Section("Background", [Markdown("b")])`)
  assert.match(String(error), /Section anchors must be unique/)
})

test('static Toc targets must still match a Section', () => {
  const { error } = inspect(`root = Col([toc, one])
toc = Toc(["Background"])
one = Section("Something else", [Markdown("a")])`)
  assert.match(String(error), /every Toc entry must target a Section anchor/)
})

test('symbol-only Section titles get distinct stable anchors', () => {
  const star = anchorSlug('★')
  const clapper = anchorSlug('🎬')
  assert.notEqual(star, clapper, 'distinct symbol titles must not collapse to one id')
  assert.match(star, /^section-[a-z0-9]+$/)
  assert.equal(anchorSlug('★'), star, 'slug must be stable')
  assert.notEqual(anchorSlug('①'), anchorSlug('②'), 'numbered symbols stay distinct')
  assert.equal(anchorSlug('南京照相馆'), '南京照相馆')
  assert.equal(anchorSlug('Hello World'), 'hello-world')
})

/** Parse a complete program and return its layout warnings. */
function layoutFor(program) {
  const result = parser.parse(program)
  assert.deepEqual(result.meta.errors ?? [], [], 'program should parse')
  return layoutWarnings(result.root)
}

test('canonical single-expression @Each row list warns (real parser AST)', () => {
  // `Col(@Each(...), 1)` parses its one positional child as an expression node,
  // not an array: this is the shape real programs use (and the one the earlier
  // hand-built AST test missed).
  const warnings = layoutFor(`root = Col([rows])
rows = Col(@Each(items, "m", Row([Box([SearchImage("still", 0.7)], null, null, null, null, null, null, 44), Text(m.t)], 3, "start")), 1)
items = [{t: "A"}, {t: "B"}, {t: "C"}]`)
  assert.ok(warnings.some(line => /gap: 1.*4px apart/.test(line)), warnings.join('\n'))
})

test('non-photo @Each rows stay silent (real parser AST)', () => {
  const warnings = layoutFor(`root = Col([rows])
rows = Col(@Each(items, "m", Row([Text(m.t)], 3, "start")), 1)
items = [{t: "A"}, {t: "B"}, {t: "C"}]`)
  assert.deepEqual(warnings.filter(line => /gap: 1/.test(line)), [])
})

test('layout warnings traverse the canonical @Each template (real parser AST)', () => {
  const warnings = layoutFor(`root = Col([rows])
rows = Col(@Each(items, "m", Col([Spacer(), Text("")], 1)))
items = [{t: "A"}]`)
  assert.ok(warnings.some(line => /Spacer\(\)` outside a/.test(line)), warnings.join('\n'))
  assert.ok(warnings.some(line => /empty .*Text/.test(line)), warnings.join('\n'))
})
