#!/usr/bin/env node
/**
 * Regenerate `src/lib/components/map/maplibre-worker-source.ts`.
 *
 * DSH's browser plugin is bundled as a single CommonJS factory, where
 * `import.meta.url` is empty. MapLibre normally derives its worker URL from
 * `import.meta.url`, so the renderer must hand it one. The worker that
 * `maplibre-gl` ships is already a self-contained module (no imports); this
 * script copies its text into a TypeScript string module, and `basemap.ts`
 * turns that string into a Blob URL via `setWorkerUrl()`.
 *
 * Run after upgrading maplibre-gl:
 *   node test/renderer/make-worker-source.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const require = createRequire(resolve(root, 'package.json'))
const pkgPath = require.resolve('maplibre-gl/package.json')
const pkg = JSON.parse(await readFile(pkgPath, 'utf8'))
const workerPath = resolve(dirname(pkgPath), 'dist/maplibre-gl-worker.mjs')
const target = resolve(root, 'src/lib/components/map/maplibre-worker-source.ts')

const source = await readFile(workerPath, 'utf8')
// The bundled worker must not import anything: a Blob worker cannot resolve
// relative specifiers, and MapLibre loads it as one file.
if (/^\s*(?:import|export)\b/m.test(source.replace(/\/\*[\s\S]*?\*\//g, ''))) {
  throw new Error('make-worker-source: maplibre worker is no longer self-contained; update basemap.ts')
}
const license = source.match(/\/\*\*[\s\S]*?@license[\s\S]*?\*\//)?.[0] ?? ''
if (!license) throw new Error('make-worker-source: maplibre worker license banner not found')
// The banner travels inside the string verbatim (a Blob worker needs the JS
// text as-is); it must not be interpolated into this file's own docblock.
const body = `/**
 * Generated by test/renderer/make-worker-source.mjs — do not edit by hand.
 *
 * MapLibre GL JS worker v${pkg.version}; the source string below keeps its own
 * BSD-3-Clause license banner (also printed here so license scanners see it):
 *
${license.split('\n').map((line) => ` * ${line.replace(/\*\//g, '* /')}`).join('\n')}
 */
export const MAPLIBRE_WORKER_VERSION = ${JSON.stringify(pkg.version)}

export const MAPLIBRE_WORKER_SOURCE = ${JSON.stringify(source)}
`
await writeFile(target, body, 'utf8')
console.log(`make-worker-source: wrote ${target} (${(source.length / 1024).toFixed(0)} kB, maplibre ${pkg.version})`)
