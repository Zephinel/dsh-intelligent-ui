#!/usr/bin/env node
/**
 * Build both halves of the DSH extension.
 *
 *   node scripts/build.mjs          # prompt + Host (lib/index.js) + client (lib/client.js)
 *   node scripts/build.mjs host
 *   node scripts/build.mjs client
 *
 * Host: one self-contained ESM file; only Node built-ins stay external.
 * Client: one self-contained CommonJS body wrapped in the DSH module-loader
 * protocol (`window.__ModuleLoader__.load({ id, factory })`), with platform
 * modules (React, Cordis, DSH client packages) resolved through the injected
 * `require`. All CSS — component library, KaTeX, MapLibre — is bundled into a
 * single stylesheet string and injected by the plugin's apply.
 */
import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const which = process.argv[2] ?? 'all'
const lib = resolve(root, 'lib')

/** Module specifiers the DSH web shell seeds into its frozen platform table. */
const PLATFORM_MODULES = [
  'react', 'react/jsx-runtime', 'react-dom', 'react-dom/client',
  '@deepseek-ai/cordis', '@tanstack/react-virtual',
  '@deepseek-ai/dsh-client-store', '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives', '@deepseek-ai/dsh-client-ui-dockkit',
]

/** Asset loaders: everything that is not text becomes an inline data URL. */
const ASSET_LOADERS = {
  '.png': 'dataurl', '.jpg': 'dataurl', '.jpeg': 'dataurl', '.webp': 'dataurl',
  '.gif': 'dataurl', '.svg': 'dataurl',
  '.woff': 'dataurl', '.woff2': 'dataurl', '.ttf': 'dataurl', '.otf': 'dataurl',
  '.eot': 'dataurl',
}

function formatBytes(bytes) {
  if (bytes > 1024 * 1024) return `${(bytes / 1024 / 1024).toFixed(2)} MB`
  if (bytes > 1024) return `${(bytes / 1024).toFixed(1)} kB`
  return `${bytes} B`
}

async function buildPrompt() {
  execFileSync(process.execPath, [resolve(root, 'scripts/generate-prompt.mjs')], { stdio: 'inherit' })
}

async function buildHost() {
  await buildPrompt()
  await mkdir(lib, { recursive: true })
  await build({
    entryPoints: [resolve(root, 'src/host/index.ts')],
    outfile: resolve(lib, 'index.js'),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    // The DSH settings schema travels as a declared runtime dependency so the
    // Host shares the composition's `@deepseek-ai/schemastery` copy.
    external: ['@deepseek-ai/schemastery'],
    sourcemap: false,
    minify: true,
    legalComments: 'none',
    loader: { '.txt': 'text', '.json': 'json' },
    banner: { js: `// ${pkg.name} host half — generated by scripts/build.mjs; do not edit.` },
  })
  const { size } = await import('node:fs').then(fs => fs.promises.stat(resolve(lib, 'index.js')))
  console.log(`host    lib/index.js   ${formatBytes(size)}`)
}

/** Wrap the bundled CJS body in the loader protocol the browser shell expects. */
function wrapClient(js, css) {
  const id = JSON.stringify(pkg.name)
  const styleId = JSON.stringify(`${pkg.name}/client`)
  const cssLiteral = JSON.stringify(css)
  return `window.__ModuleLoader__.load({
  id: ${id},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    // Bundle-owned stylesheet: injected once per document and removed on dispose.
    var __css = ${cssLiteral};
    function __installStyles() {
      var tag = document.querySelector('style[data-plugin-css=' + JSON.stringify(${styleId}) + ']');
      if (tag === null) {
        tag = document.createElement('style');
        tag.dataset.plugin = ${id};
        tag.dataset.pluginCss = ${styleId};
        tag.textContent = __css;
        document.head.appendChild(tag);
      }
      return function () { if (tag.parentNode !== null) tag.parentNode.removeChild(tag); };
    }
    var __disposeStyles = __installStyles();
    try {
${js}
    } catch (__error) { __disposeStyles(); throw __error; }
    return module.exports;
  },
});
`
}

async function buildClient() {
  await mkdir(lib, { recursive: true })
  const result = await build({
    entryPoints: [resolve(root, 'src/client/index.tsx')],
    bundle: true,
    platform: 'browser',
    format: 'cjs',
    target: 'es2022',
    jsx: 'automatic',
    jsxImportSource: 'react',
    outdir: lib,
    entryNames: 'client',
    write: false,
    sourcemap: false,
    minify: true,
    legalComments: 'none',
    external: PLATFORM_MODULES,
    define: { 'process.env.NODE_ENV': '"production"' },
    loader: ASSET_LOADERS,
    logLevel: 'warning',
  })
  let js = ''
  let css = ''
  for (const file of result.outputFiles) {
    if (file.path.endsWith('.js')) js = file.text
    else if (file.path.endsWith('.css')) css += file.text
  }
  if (js === '') throw new Error('client build emitted no JavaScript output')
  const wrapped = wrapClient(js, css)
  await writeFile(resolve(lib, 'client.js'), wrapped, 'utf8')
  console.log(`client  lib/client.js  ${formatBytes(Buffer.byteLength(wrapped))} (js ${formatBytes(Buffer.byteLength(js))}, css ${formatBytes(Buffer.byteLength(css))})`)
}

if (which === 'all' || which === 'host') await buildHost()
if (which === 'all' || which === 'client') await buildClient()

// The browser loader addresses a plugin by its package name, and the emitted
// wrapper registers `module-loader id = package.json name`. A running DSH web
// host caches the client module graph and its bundle revisions, so rebuilding
// (especially after a name change) without restarting it can serve a revision
// whose registration id no longer matches the graph row — the page then reports
// "loaded without registering <id> via __ModuleLoader__.load". The restart
// recomputes the graph; a bare refresh is not enough.
if (which === 'all' || which === 'client') {
  console.log('note: restart a running DSH web service after rebuilding client plugins (the client module graph caches revisions).')
}
